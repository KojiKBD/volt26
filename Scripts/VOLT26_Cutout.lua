-- VOLT26.Cutout: "ransom note" lettering for strings only known at runtime.
--
-- Every letter gets its own face, case, size, tilt and baseline offset, white on
-- a merged black backing, and some letters are inverted inside a box.  The
-- choices are drawn from a generator seeded with the string itself, so a given
-- name always comes out the same way.
--
-- The module has two halves:
--   * VOLT26.Cutout.Layout(text, opts) is behaviour only: it returns the letters
--     and their geometry as plain data and touches no actors.
--   * VOLT26.Cutout.CreateSlot(params) is the presentation: an actor that draws a
--     layout once into an ActorFrameTexture and shows the result as a Sprite, so
--     nothing is laid out or redrawn per frame.  The texture is only redrawn
--     when the slot is given a different string.
--
-- Faces are the bitmap fonts in Fonts/Cutout; their glyph metrics come from
-- Scripts/VOLT26_CutoutMetrics.lua.  Both are generated by
-- tools/cutout-fonts/generate.py.

VOLT26.Cutout = VOLT26.Cutout or {}
local Cutout = VOLT26.Cutout

-- Tunables.  Sizes are in theme units (the screen is SCREEN_HEIGHT units tall).
-- Any of these can be overridden per slot through CreateSlot's `opts`.
Cutout.Defaults = {
	base = 22,            -- nominal letter size (em)
	chaos = 0.45,         -- scales baseline jitter and per-letter rotation
	boxChance = 0.28,     -- chance a letter is inverted inside a box
	upperChance = 0.68,   -- chance a letter is upper case (typed case is ignored)
	sizeMin = 0.82,       -- letter size range, as a fraction of `base`
	sizeMax = 1.22,
	lowerBoost = 1.08,    -- lower-case letters are drawn this much larger
	outline = 0.11,       -- backing thickness, as a fraction of `base`
	tiltDeg = -5,         -- rotation of the whole block
	fg = color("#FFFFFF"),
	bk = color("#000000"),
}

-- Screens that show the cutout lettering in place of plain text.
Cutout.Screens = {
	ScreenTitleMenu = true,
	-- The menus between the title and song selection share its footer.
	ScreenSelectStyle = true,
	ScreenSelectPlayMode = true,
	ScreenSelectPlayMode2 = true,
	ScreenVOLT26SelectMode = true,
}

function Cutout.IsEnabledOn(screenName)
	return screenName ~= nil and Cutout.Screens[screenName] == true
end

-- ---------------------------------------------------------------------------
-- Deterministic randomness.  Lua 5.1 has no bit operations, so this is the
-- Park-Miller "minimal standard" generator, which stays exact in doubles.

local MOD = 2147483647

local function hash(text)
	local h = 5381
	for i = 1, #text do
		h = (h * 33 + text:byte(i)) % MOD
	end
	if h == 0 then h = 1 end
	return h
end

local function generator(seed)
	local state = seed
	-- Discard a few values so short, similar names diverge quickly.
	for _ = 1, 3 do state = (state * 48271) % MOD end
	return function()
		state = (state * 48271) % MOD
		return (state - 1) / (MOD - 1)
	end
end

Cutout.Hash = hash

-- ---------------------------------------------------------------------------
-- Layout

local function characters(text)
	local list = {}
	for ch in text:gmatch("[%z\1-\127\194-\244][\128-\191]*") do
		list[#list+1] = ch
	end
	return list
end

local function merge(opts)
	local o = {}
	for k, v in pairs(Cutout.Defaults) do o[k] = v end
	if opts then for k, v in pairs(opts) do o[k] = v end end
	return o
end

-- Picks a face that has `ch`, starting from a random one and never repeating
-- `last` unless no other face can draw the letter.
local function pickFace(faces, ch, last, R)
	local count = #faces
	local start = math.floor(R() * count) + 1
	for step = 0, count - 1 do
		local index = (start + step - 1) % count + 1
		if index ~= last and faces[index].glyphs[ch] then return index end
	end
	if last and faces[last].glyphs[ch] then return last end
	return nil
end

-- Returns a table describing the lettering, or nil plus the first character no
-- face can draw.  All sizes are in the same units as opts.base.
--
--   layout.glyphs[i] = { face, font, ch, px, w, asc, desc, box, pad, x, dy, rot }
--     x       left edge of the letter's advance box (inside its box padding)
--     dy      baseline offset; rot is in degrees, about the letter's centre on
--             its baseline
--   layout.width, layout.height   unrotated block size
--   layout.baseline               baseline y inside the block
--   layout.bounds                 {minX, minY, maxX, maxY} of everything drawn,
--                                 tilt included, relative to the block centre
function Cutout.Layout(text, opts)
	local M = VOLT26.CutoutMetrics
	if not M then return nil, "metrics" end
	local o = merge(opts)
	local base = o.base
	local outline = base * o.outline
	local faces = M.faces
	local R = generator(hash(text or ""))

	local glyphs = {}
	local x, last = 0, nil
	for _, raw in ipairs(characters(text or "")) do
		if raw == " " then
			x = x + base * 0.38
		else
			local wantUpper = R() < o.upperChance
			local ch = wantUpper and (M.upper[raw] or raw) or (M.lower[raw] or raw)
			local face = pickFace(faces, ch, last, R)
			if not face then
				-- One case is missing from the faces (Æ, Œ): use the other one.
				local other = M.lower[ch] or M.upper[ch]
				if other then
					ch = other
					face = pickFace(faces, ch, last, R)
				end
			end
			if not face then return nil, raw end
			last = face

			local isLower = M.upper[ch] ~= nil
			local px = base * (o.sizeMin + R() * (o.sizeMax - o.sizeMin)) * (isLower and o.lowerBoost or 1)
			local metric = faces[face].glyphs[ch]
			local box = R() < o.boxChance
			local pad = box and px * 0.07 or 0
			local g = {
				face = face, font = faces[face].font, ch = ch, px = px,
				w = metric[1] * px, asc = metric[2] * px, desc = metric[3] * px,
				box = box, pad = pad, x = x + pad,
				dy = (R() - 0.5) * base * 0.32 * o.chaos,
				rot = math.deg((R() - 0.5) * 0.5 * o.chaos),
			}
			glyphs[#glyphs+1] = g
			x = x + g.w + pad * 2 + base * (box and 0.05 or -0.015)
		end
	end
	if #glyphs == 0 then return nil, "" end

	local layout = {
		glyphs = glyphs, options = o, outline = outline,
		width = math.max(1, x), height = base * 1.12,
	}
	layout.baseline = layout.height * 0.84

	-- Bounds: every letter's backing rectangle, rotated with the letter, then
	-- with the whole block, plus the drop shadow offset.
	local cx, cy = layout.width / 2, layout.height / 2
	local tilt = math.rad(o.tiltDeg)
	local ct, st = math.cos(tilt), math.sin(tilt)
	local minX, minY, maxX, maxY = math.huge, math.huge, -math.huge, -math.huge
	local shadowX, shadowY = outline * 0.55, outline * 0.7
	for _, g in ipairs(glyphs) do
		local grow = g.box and outline * 0.8 or outline
		local left, right = -g.w / 2 - g.pad - grow, g.w / 2 + g.pad + grow
		local top, bottom = -g.asc - g.pad - grow, g.desc + g.pad + grow
		local r = math.rad(g.rot)
		local cr, sr = math.cos(r), math.sin(r)
		local gx, gy = g.x + g.w / 2 - cx, layout.baseline + g.dy - cy
		for _, corner in ipairs({{left, top}, {right, top}, {left, bottom}, {right, bottom}}) do
			for _, shift in ipairs({{0, 0}, {shadowX, shadowY}}) do
				local px = gx + corner[1] * cr - corner[2] * sr + shift[1]
				local py = gy + corner[1] * sr + corner[2] * cr + shift[2]
				local tx, ty = px * ct - py * st, px * st + py * ct
				if tx < minX then minX = tx end
				if tx > maxX then maxX = tx end
				if ty < minY then minY = ty end
				if ty > maxY then maxY = ty end
			end
		end
	end
	layout.bounds = {minX, minY, maxX, maxY}
	return layout
end

-- ---------------------------------------------------------------------------
-- Presentation

-- The backing is drawn by stamping each black letter around a circle of radius
-- `outline`, once around the letter and once around the drop-shadow offset.
-- Eight directions left visibly serrated edges in the engine; sixteen keep the
-- outline's deviation from a true circle under a tenth of its radius.
--
-- The letters are laid out once per pass and stamped at every offset of that
-- pass through ActorProxies, so a string costs three ActorFrameTexture frames
-- (centre backing, ring backing, letters) and nothing afterwards.  Rendering
-- one offset per frame took 35 frames, over half a second at 60 Hz and twice
-- that on a slow machine, which is how long a new name stayed invisible.
local RING = 16

local function backingOffsets(outline)
	local list = {}
	for _, centre in ipairs({{outline * 0.55, outline * 0.7}, {0, 0}}) do
		list[#list+1] = {centre[1], centre[2], true}
		for i = 0, RING - 1 do
			local a = i * 2 * math.pi / RING
			list[#list+1] = {centre[1] + math.cos(a) * outline, centre[2] + math.sin(a) * outline, false}
		end
	end
	return list
end

-- The three passes of a string: every stamp in a backing pass is black, so
-- the order of the stamps within a pass does not matter.
local function backingPasses(outline)
	local centres, ring = {}, {}
	for _, offset in ipairs(backingOffsets(outline)) do
		if offset[3] then centres[#centres+1] = offset else ring[#ring+1] = offset end
	end
	return {
		{ style = {0, 0, true},  offsets = centres },
		{ style = {0, 0, false}, offsets = ring },
		{ style = nil,           offsets = {{0, 0}} },
	}
end

-- The passes that draw `layout` (for the texture cache).
function Cutout.Passes(layout)
	return backingPasses(layout.outline)
end

-- Enough proxies for the largest pass (the ring around both centres).
local PROXIES = 2 * RING

-- Pixels of empty border around the lettering in a texture.
Cutout.Margin = 2

-- Display pixels per theme unit.  Lettering is drawn at the display's
-- resolution, not the theme's, so its sprite maps 1:1 onto screen pixels.
function Cutout.DisplayScale()
	if DISPLAY and DISPLAY.GetDisplayHeight then
		return math.min(3, math.max(1, DISPLAY:GetDisplayHeight() / SCREEN_HEIGHT))
	end
	return 1
end

-- The zoom from layout units to texture pixels for a layout shrunk (never
-- grown) to fit maxW x maxH theme units, drawn at `scale` pixels per unit.
function Cutout.FitZoom(layout, maxW, maxH, scale)
	local b = layout.bounds
	return math.min(1, maxW / (b[3] - b[1]), maxH / (b[4] - b[2])) * (scale or 1)
end

-- Cutout.Defaults merged with a slot's overrides.
Cutout.MergeOptions = merge

-- A string that identifies a set of merged options, for the texture cache's
-- keys.  Numbers are rounded so the same size worked out in two places (a
-- screen and the warm-up) still matches.
local SIGNATURE_KEYS = {
	"base", "chaos", "boxChance", "upperChance", "sizeMin", "sizeMax",
	"lowerBoost", "outline", "tiltDeg", "fg", "bk",
}

local function signaturePart(value)
	if type(value) == "number" then return ("%.3f"):format(value) end
	if type(value) == "table" then
		return ("%.3f,%.3f,%.3f,%.3f"):format(value[1] or 0, value[2] or 0, value[3] or 0, value[4] or 1)
	end
	return tostring(value)
end

function Cutout.Signature(o)
	local parts = {}
	for i, key in ipairs(SIGNATURE_KEYS) do parts[i] = signaturePart(o[key]) end
	return table.concat(parts, ";")
end

-- The stamper: the actors that draw one layout, pass by pass, into whatever
-- ActorFrameTexture draws them.  Shared by the slots (each has its own) and
-- the texture cache (one for the whole session, Scripts/VOLT26_CutoutCache.lua).
--
-- One BitmapText (with its box Quad) per face per letter: a BitmapText's face
-- is fixed when it is built, and no face can appear more than every other
-- letter, so `maxChars` letters need ceil(maxChars / 2) stamps of each face.
-- The block itself is never drawn directly: the proxies stamp it at every
-- offset of a pass.
--
--   stamper.Actor()                  the Def to place (once), a tilt frame
--   stamper.Frame(layout, x, y, zoom) puts the block's centre at (x, y) in
--                                    texture pixels, `zoom` pixels per unit
--   stamper.Pass(layout, pass)       sets the stamps and proxies for a pass
--                                    (one of Cutout.Passes(layout))
-- A stamper is several hundred actors (six faces, half the letters each, a
-- box per letter, the ring of proxies) that are only needed for the three
-- frames a string takes to render.  Hidden actors are still updated every
-- frame, so whatever holds a stamper hibernates it between renders
-- (Cutout.ASLEEP; a hibernating actor skips its update and its children's
-- and is not drawn) and wakes it for each pass.
Cutout.ASLEEP = 1e9

-- How long a slot waits, in seconds, before it stops waiting for the cache
-- (PATIENCE_CACHE), for the tweens above it (PATIENCE_TWEEN) and for its
-- ancestors to be fully opaque (PATIENCE_ALPHA) before drawing its string.
Cutout.PATIENCE_CACHE = 1.5
Cutout.PATIENCE_TWEEN = 1.0
Cutout.PATIENCE_ALPHA = 3.0

function Cutout.NewStamper(maxChars)
	local faces = VOLT26.CutoutMetrics and VOLT26.CutoutMetrics.faces or {}
	local perFace = math.ceil(maxChars / 2)
	local S = { stamps = {}, proxies = {}, capacity = maxChars }

	local function place(layout, offset)
		local o = layout.options
		local outline = layout.outline
		local used = {}
		for f = 1, #faces do used[f] = 0 end
		for f = 1, #faces do
			for _, stamp in ipairs(S.stamps[f]) do stamp.frame:visible(false) end
		end
		for i, g in ipairs(layout.glyphs) do
			used[g.face] = used[g.face] + 1
			local stamp = S.stamps[g.face][used[g.face]]
			if stamp then
				local dx, dy = 0, 0
				if offset then dx, dy = offset[1], offset[2] end
				-- Ring stamps draw plain letters only; boxes are already grown
				-- by their own backing rectangle on the centre stamps.
				local show = (not offset) or offset[3] or not g.box
				stamp.frame:visible(show):draworder(i)
					:xy(g.x + g.w / 2 + dx, layout.baseline + g.dy + dy):rotationz(g.rot)
				stamp.text:settext(g.ch):zoom(g.px / VOLT26.CutoutMetrics.em)
				local grow = 0
				if offset then grow = outline * 0.8 end
				if g.box then
					stamp.quad:visible(true)
						:zoomto(g.w + 2 * (g.pad + grow), g.asc + g.desc + 2 * (g.pad + grow))
						:y((g.desc - g.asc) / 2)
						:diffuse(offset and o.bk or o.fg)
				else
					stamp.quad:visible(false)
				end
				if offset or g.box then
					stamp.text:diffuse(o.bk)
				else
					stamp.text:diffuse(o.fg)
				end
			end
		end
		S.block:SortByDrawOrder()
	end

	function S.Frame(layout, x, y, zoom)
		S.tilt:xy(x, y):zoom(zoom):rotationz(layout.options.tiltDeg)
		S.block:xy(-layout.width / 2, -layout.height / 2)
	end

	function S.Pass(layout, pass)
		place(layout, pass.style)
		for i, proxy in ipairs(S.proxies) do
			local offset = pass.offsets[i]
			proxy:visible(offset ~= nil)
			if offset then proxy:xy(offset[1], offset[2]) end
		end
	end

	function S.Actor()
		local block = Def.ActorFrame{
			Name="Block",
			InitCommand=function(self) S.block = self; self:visible(false) end,
		}
		for f, face in ipairs(faces) do
			for k = 1, perFace do
				block[#block+1] = Def.ActorFrame{
					InitCommand=function(self)
						S.stamps[f] = S.stamps[f] or {}
						S.stamps[f][k] = {
							frame = self,
							quad = self:GetChild("Box"),
							text = self:GetChild("Letter"),
						}
						self:visible(false)
					end,
					Def.Quad{ Name="Box" },
					LoadFont(face.font)..{
						Name="Letter",
						-- Bottom alignment puts the baseline of a single line at y=0.
						InitCommand=function(self) self:halign(0.5):valign(1):settext("") end,
					},
				}
			end
		end
		local tilt = Def.ActorFrame{
			InitCommand=function(self) S.tilt = self end,
			block,
		}
		for i = 1, PROXIES do
			tilt[#tilt+1] = Def.ActorProxy{
				InitCommand=function(self)
					S.proxies[i] = self
					self:SetTarget(self:GetParent():GetChild("Block"))
					self:visible(false)
				end,
			}
		end
		return tilt
	end

	return S
end

local slotCount = 0

-- params:
--   maxW, maxH   the space the lettering must fit, in theme units
--   halign       0 left, 0.5 centre, 1 right: which edge of the lettering sits
--                on the slot's x
--   valign       0 top, 0.5 centre, 1 bottom, likewise for y
--   maxChars     longest string drawn in cutout (longer strings fall back)
--   opts         overrides for Cutout.Defaults
--   fallbackFont font for strings the cutout faces cannot draw
--   x, y         optional position
--   onInit       optional function(slot) called from the slot's InitCommand
--                (a caller's own InitCommand would replace the slot's)
--   onReady      optional function(slot) called when a string has finished
--                rendering (or fallen back to plain text), e.g. to swap two
--                slots so a name never disappears while its successor renders
--   held         start held: the string is rendered but not shown until
--                "CutoutHold" releases it, so it can be prepared off-stage
--
-- Commands: "CutoutSet" with {text=...} draws a string (no-op when unchanged);
-- "CutoutHold" with {held=true|false} hides or shows the finished lettering.
--
-- A string is taken from the shared texture cache (VOLT26.Cutout.Cache,
-- Scripts/VOLT26_CutoutCache.lua) when it can hold it: a string already
-- there, rendered earlier or by the startup warm-up, shows at once, and a new
-- one is rendered there in three frames.  The slot renders a string itself
-- only when the cache cannot take it (no cache, string too large, every page
-- in use).
function Cutout.CreateSlot(params)
	params = params or {}
	slotCount = slotCount + 1
	local textureName = "VOLT26Cutout" .. slotCount
	local opts = merge(params.opts)
	local signature = Cutout.Signature(opts)
	local maxW, maxH = params.maxW or 240, params.maxH or opts.base * 2
	local halign, valign = params.halign or 0.5, params.valign or 0.5
	local maxChars = params.maxChars or 16
	local stamper = Cutout.NewStamper(maxChars)

	local scale = Cutout.DisplayScale()
	local margin = Cutout.Margin
	local texW = math.ceil(maxW * scale) + margin * 2
	local texH = math.ceil(maxH * scale) + margin * 2

	local state = {
		text = nil, layout = nil, passes = nil, pass = 0, held = params.held == true,
		-- The cache entry shown (or awaited, while `waiting`).
		entry = nil, waiting = false,
	}

	local function frameBlock(layout)
		local b = layout.bounds
		local zoom = Cutout.FitZoom(layout, maxW, maxH, scale)
		local x = (margin - b[1] * zoom) * (1 - halign) + (texW - margin - b[3] * zoom) * halign
		if halign == 0.5 then x = texW / 2 - (b[1] + b[3]) / 2 * zoom end
		local y = (margin - b[2] * zoom) * (1 - valign) + (texH - margin - b[4] * zoom) * valign
		if valign == 0.5 then y = texH / 2 - (b[2] + b[4]) / 2 * zoom end
		stamper.Frame(layout, x, y, zoom)
	end

	local function showPlain(text)
		state.sprite:visible(false)
		state.cached:visible(false)
		state.aft:visible(false)
		state.passes = nil
		state.layout = nil
		state.entry, state.waiting = nil, false
		state.plain:visible(not state.held):settext(text or "")
		if params.onReady then params.onReady(state.self) end
	end

	-- Shows the cache entry's region of its page: the region holds the
	-- lettering with the same margin the slot's own texture would, so it is
	-- aligned on the slot the same way.
	local function showEntry(slot)
		local e = state.entry
		state.waiting = false
		local W, H = e.pageW, e.pageH
		state.cached:SetTexture(e.texture)
			:cropleft(e.x / W):cropright(1 - (e.x + e.w) / W)
			:croptop(e.y / H):cropbottom(1 - (e.y + e.h) / H)
			:xy(-(e.x + halign * e.w) / scale, -(e.y + valign * e.h) / scale)
			:visible(not state.held)
		if params.onReady then params.onReady(slot) end
	end

	local function setText(slot, text)
		state.text = text
		state.since = GetTimeSinceStart()
		state.passes = nil
		state.entry, state.waiting = nil, false
		state.cached:visible(false)
		local chars = select(2, text:gsub("[^\128-\191]", ""))
		local layout = chars <= maxChars and Cutout.Layout(text, opts) or nil
		if not layout then
			showPlain(text)
			return
		end
		state.plain:visible(false)
		state.sprite:visible(false)
		state.layout = layout

		local cache = Cutout.Cache
		local entry = cache and cache.Acquire
			and cache.Acquire(text, signature, layout, Cutout.FitZoom(layout, maxW, maxH, scale))
		if entry then
			state.aft:visible(false)
			state.entry = entry
			if entry.ready then showEntry(slot) else state.waiting = true end
			return
		end

		frameBlock(layout)
		state.passes = backingPasses(layout.outline)
		state.pass = 0
	end

	-- A pass only lands in the texture if the slot is actually drawn, and a
	-- parent's alpha would be baked into the stamps, so passes wait until the
	-- slot and every ancestor are visible, fully opaque and not tweening.
	-- GetDiffuseAlpha reports where a tween is heading, not where it is, so a
	-- fade in progress is caught by its remaining tween time instead.
	--
	-- A screen that keeps something moving above the slot (an intro, a
	-- marquee, a long sleep on its root) would hold the string back for good,
	-- so the wait is limited: after PATIENCE_TWEEN seconds a tween no longer
	-- stops a pass, and after PATIENCE_ALPHA neither does an ancestor's alpha
	-- (faint lettering is better than none).  Visibility always counts.
	local function drawnOpaque(actor, waited)
		local ignoreTween = waited >= Cutout.PATIENCE_TWEEN
		local ignoreAlpha = waited >= Cutout.PATIENCE_ALPHA
		while actor do
			if not actor:GetVisible()
			or (not ignoreAlpha and actor:GetDiffuseAlpha() < 1)
			or (not ignoreTween and actor:GetTweenTimeLeft() > 0) then return false end
			actor = actor:GetParent()
		end
		return true
	end

	local function waited()
		return GetTimeSinceStart() - (state.since or 0)
	end

	local function update(slot)
		local e = state.entry
		if e then
			if e.dead then
				-- The cache dropped it (the display was reset): ask again.
				setText(slot, state.text)
				return
			end
			-- Marks the entry in use, so the cache does not reclaim it.
			Cutout.Cache.Touch(e)
			if state.waiting and e.ready then showEntry(slot) return end
			-- The cache is taking too long (a long queue, or it cannot draw
			-- at all just now): the slot renders the string itself.
			if state.waiting and state.layout and waited() >= Cutout.PATIENCE_CACHE then
				state.entry, state.waiting = nil, false
				frameBlock(state.layout)
				state.passes = backingPasses(state.layout.outline)
				state.pass = 0
			end
			return
		end

		if not state.passes or not drawnOpaque(slot, waited()) then return end
		state.pass = state.pass + 1
		local pass = state.passes[state.pass]
		if not pass then
			state.passes = nil
			state.aft:visible(false):hibernate(Cutout.ASLEEP)
			state.sprite:visible(not state.held)
			if params.onReady then params.onReady(slot) end
			return
		end
		-- The first pass starts from an empty texture; later passes add to it.
		state.aft:EnablePreserveTexture(state.pass > 1)
		state.clear:visible(state.pass == 1)
		stamper.Pass(state.layout, pass)
		state.aft:hibernate(0):visible(true)
	end

	return Def.ActorFrame{
		InitCommand=function(self)
			state.self = self
			if params.x then self:xy(params.x, params.y or 0) end
			self:SetUpdateFunction(update)
			if params.onInit then params.onInit(self) end
		end,
		CutoutHoldCommand=function(self, p)
			state.held = p and p.held == true
			if state.entry then
				if not state.waiting then state.cached:visible(not state.held) end
			elseif state.layout and not state.passes then
				state.sprite:visible(not state.held)
			elseif not state.layout and state.text then
				state.plain:visible(not state.held)
			end
		end,
		CutoutSetCommand=function(self, p)
			local text = p and p.text or ""
			if text == state.text then
				-- Already drawn (or drawing): a finished slot still reports ready.
				if not state.passes and not state.waiting and params.onReady then params.onReady(self) end
				return
			end
			setText(self, text)
		end,

		Def.ActorFrameTexture{
			InitCommand=function(self)
				state.aft = self
				self:setsize(texW, texH)
				self:SetTextureName(textureName)
				self:EnableAlphaBuffer(true)
				-- Each pass adds a stamp; the first pass clears the texture
				-- (see update()).
				self:EnablePreserveTexture(true)
				self:Create()
				self:visible(false):hibernate(Cutout.ASLEEP)
			end,
			Def.Quad{
				InitCommand=function(self)
					state.clear = self
					-- Belt and braces for the first pass: CopySrc overwrites the
					-- texture with this colour.  The engine skips actors whose
					-- alpha is exactly 0, so it carries an alpha that still
					-- rounds to 0 in an 8-bit target.
					self:halign(0):valign(0):zoomto(texW, texH)
						:diffuse(0, 0, 0, 0.001):blend("BlendMode_CopySrc"):visible(false)
				end,
			},
			stamper.Actor(),
		},
		Def.Sprite{
			InitCommand=function(self)
				state.sprite = self
				self:SetTexture(state.aft:GetTexture())
				self:align(halign, valign):zoom(1 / scale):visible(false)
			end,
		},
		-- A string from the texture cache: a region of one of its pages.
		Def.Sprite{
			InitCommand=function(self)
				state.cached = self
				self:align(0, 0):zoom(1 / scale):visible(false)
			end,
		},
		LoadFont(params.fallbackFont or "Common Normal")..{
			InitCommand=function(self)
				state.plain = self
				self:align(halign, valign):visible(false)
				if params.fallbackZoom then self:zoom(params.fallbackZoom) end
				self:maxwidth(maxW / (params.fallbackZoom or 1))
			end,
		},
	}
end
