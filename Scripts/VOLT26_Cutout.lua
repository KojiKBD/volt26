-- VOLT26.Cutout: "ransom note" lettering for strings only known at runtime.
--
-- Every letter gets its own face, case, size, tilt and baseline offset, white on
-- a merged black backing, and some letters are inverted inside a box.  The
-- choices are drawn from a generator seeded with the string itself, so a given
-- name always comes out the same way.
--
-- The module has two halves:
--   * VOLT26.Cutout.Layout(text, opts) is behaviour only: it returns the letters
--     and their geometry as plain data and touches no actors.
--   * VOLT26.Cutout.CreateSlot(params) is the presentation: an actor that draws a
--     layout once into an ActorFrameTexture and shows the result as a Sprite, so
--     nothing is laid out or redrawn per frame.  The texture is only redrawn
--     when the slot is given a different string.
--
-- Faces are the bitmap fonts in Fonts/Cutout; their glyph metrics come from
-- Scripts/VOLT26_CutoutMetrics.lua.  Both are generated by
-- tools/cutout-fonts/generate.py.

VOLT26.Cutout = VOLT26.Cutout or {}
local Cutout = VOLT26.Cutout

-- Tunables.  Sizes are in theme units (the screen is SCREEN_HEIGHT units tall).
-- Any of these can be overridden per slot through CreateSlot's `opts`.
Cutout.Defaults = {
	base = 22,            -- nominal letter size (em)
	chaos = 0.45,         -- scales baseline jitter and per-letter rotation
	boxChance = 0.28,     -- chance a letter is inverted inside a box
	upperChance = 0.68,   -- chance a letter is upper case (typed case is ignored)
	sizeMin = 0.82,       -- letter size range, as a fraction of `base`
	sizeMax = 1.22,
	lowerBoost = 1.08,    -- lower-case letters are drawn this much larger
	outline = 0.11,       -- backing thickness, as a fraction of `base`
	tiltDeg = -5,         -- rotation of the whole block
	fg = color("#FFFFFF"),
	bk = color("#000000"),
}

-- Screens that show the cutout lettering in place of plain text.
Cutout.Screens = {
	ScreenTitleMenu = true,
}

function Cutout.IsEnabledOn(screenName)
	return screenName ~= nil and Cutout.Screens[screenName] == true
end

-- ---------------------------------------------------------------------------
-- Deterministic randomness.  Lua 5.1 has no bit operations, so this is the
-- Park-Miller "minimal standard" generator, which stays exact in doubles.

local MOD = 2147483647

local function hash(text)
	local h = 5381
	for i = 1, #text do
		h = (h * 33 + text:byte(i)) % MOD
	end
	if h == 0 then h = 1 end
	return h
end

local function generator(seed)
	local state = seed
	-- Discard a few values so short, similar names diverge quickly.
	for _ = 1, 3 do state = (state * 48271) % MOD end
	return function()
		state = (state * 48271) % MOD
		return (state - 1) / (MOD - 1)
	end
end

Cutout.Hash = hash

-- ---------------------------------------------------------------------------
-- Layout

local function characters(text)
	local list = {}
	for ch in text:gmatch("[%z\1-\127\194-\244][\128-\191]*") do
		list[#list+1] = ch
	end
	return list
end

local function merge(opts)
	local o = {}
	for k, v in pairs(Cutout.Defaults) do o[k] = v end
	if opts then for k, v in pairs(opts) do o[k] = v end end
	return o
end

-- Picks a face that has `ch`, starting from a random one and never repeating
-- `last` unless no other face can draw the letter.
local function pickFace(faces, ch, last, R)
	local count = #faces
	local start = math.floor(R() * count) + 1
	for step = 0, count - 1 do
		local index = (start + step - 1) % count + 1
		if index ~= last and faces[index].glyphs[ch] then return index end
	end
	if last and faces[last].glyphs[ch] then return last end
	return nil
end

-- Returns a table describing the lettering, or nil plus the first character no
-- face can draw.  All sizes are in the same units as opts.base.
--
--   layout.glyphs[i] = { face, font, ch, px, w, asc, desc, box, pad, x, dy, rot }
--     x       left edge of the letter's advance box (inside its box padding)
--     dy      baseline offset; rot is in degrees, about the letter's centre on
--             its baseline
--   layout.width, layout.height   unrotated block size
--   layout.baseline               baseline y inside the block
--   layout.bounds                 {minX, minY, maxX, maxY} of everything drawn,
--                                 tilt included, relative to the block centre
function Cutout.Layout(text, opts)
	local M = VOLT26.CutoutMetrics
	if not M then return nil, "metrics" end
	local o = merge(opts)
	local base = o.base
	local outline = base * o.outline
	local faces = M.faces
	local R = generator(hash(text or ""))

	local glyphs = {}
	local x, last = 0, nil
	for _, raw in ipairs(characters(text or "")) do
		if raw == " " then
			x = x + base * 0.38
		else
			local wantUpper = R() < o.upperChance
			local ch = wantUpper and (M.upper[raw] or raw) or (M.lower[raw] or raw)
			local face = pickFace(faces, ch, last, R)
			if not face then
				-- One case is missing from the faces (Æ, Œ): use the other one.
				local other = M.lower[ch] or M.upper[ch]
				if other then
					ch = other
					face = pickFace(faces, ch, last, R)
				end
			end
			if not face then return nil, raw end
			last = face

			local isLower = M.upper[ch] ~= nil
			local px = base * (o.sizeMin + R() * (o.sizeMax - o.sizeMin)) * (isLower and o.lowerBoost or 1)
			local metric = faces[face].glyphs[ch]
			local box = R() < o.boxChance
			local pad = box and px * 0.07 or 0
			local g = {
				face = face, font = faces[face].font, ch = ch, px = px,
				w = metric[1] * px, asc = metric[2] * px, desc = metric[3] * px,
				box = box, pad = pad, x = x + pad,
				dy = (R() - 0.5) * base * 0.32 * o.chaos,
				rot = math.deg((R() - 0.5) * 0.5 * o.chaos),
			}
			glyphs[#glyphs+1] = g
			x = x + g.w + pad * 2 + base * (box and 0.05 or -0.015)
		end
	end
	if #glyphs == 0 then return nil, "" end

	local layout = {
		glyphs = glyphs, options = o, outline = outline,
		width = math.max(1, x), height = base * 1.12,
	}
	layout.baseline = layout.height * 0.84

	-- Bounds: every letter's backing rectangle, rotated with the letter, then
	-- with the whole block, plus the drop shadow offset.
	local cx, cy = layout.width / 2, layout.height / 2
	local tilt = math.rad(o.tiltDeg)
	local ct, st = math.cos(tilt), math.sin(tilt)
	local minX, minY, maxX, maxY = math.huge, math.huge, -math.huge, -math.huge
	local shadowX, shadowY = outline * 0.55, outline * 0.7
	for _, g in ipairs(glyphs) do
		local grow = g.box and outline * 0.8 or outline
		local left, right = -g.w / 2 - g.pad - grow, g.w / 2 + g.pad + grow
		local top, bottom = -g.asc - g.pad - grow, g.desc + g.pad + grow
		local r = math.rad(g.rot)
		local cr, sr = math.cos(r), math.sin(r)
		local gx, gy = g.x + g.w / 2 - cx, layout.baseline + g.dy - cy
		for _, corner in ipairs({{left, top}, {right, top}, {left, bottom}, {right, bottom}}) do
			for _, shift in ipairs({{0, 0}, {shadowX, shadowY}}) do
				local px = gx + corner[1] * cr - corner[2] * sr + shift[1]
				local py = gy + corner[1] * sr + corner[2] * cr + shift[2]
				local tx, ty = px * ct - py * st, px * st + py * ct
				if tx < minX then minX = tx end
				if tx > maxX then maxX = tx end
				if ty < minY then minY = ty end
				if ty > maxY then maxY = ty end
			end
		end
	end
	layout.bounds = {minX, minY, maxX, maxY}
	return layout
end

-- ---------------------------------------------------------------------------
-- Presentation

-- The backing is drawn by stamping each black letter around a circle of radius
-- `outline`, once around the letter and once around the drop-shadow offset.
-- Each stamp is one frame of the texture's render, so a string costs one
-- ActorFrameTexture pass per offset, once, and nothing afterwards.  Eight
-- directions left visibly serrated edges in the engine; sixteen keep the
-- outline's deviation from a true circle under a tenth of its radius.
local RING = 16

local function backingOffsets(outline)
	local list = {}
	for _, centre in ipairs({{outline * 0.55, outline * 0.7}, {0, 0}}) do
		list[#list+1] = {centre[1], centre[2], true}
		for i = 0, RING - 1 do
			local a = i * 2 * math.pi / RING
			list[#list+1] = {centre[1] + math.cos(a) * outline, centre[2] + math.sin(a) * outline, false}
		end
	end
	return list
end

local slotCount = 0

-- params:
--   maxW, maxH   the space the lettering must fit, in theme units
--   halign       0 left, 0.5 centre, 1 right: which edge of the lettering sits
--                on the slot's x
--   valign       0 top, 0.5 centre, 1 bottom, likewise for y
--   maxChars     longest string drawn in cutout (longer strings fall back)
--   opts         overrides for Cutout.Defaults
--   fallbackFont font for strings the cutout faces cannot draw
--   x, y         optional position
--   onInit       optional function(slot) called from the slot's InitCommand
--                (a caller's own InitCommand would replace the slot's)
--
-- Commands: "CutoutSet" with {text=...} draws a string (no-op when unchanged).
function Cutout.CreateSlot(params)
	params = params or {}
	slotCount = slotCount + 1
	local textureName = "VOLT26Cutout" .. slotCount
	local opts = merge(params.opts)
	local maxW, maxH = params.maxW or 240, params.maxH or opts.base * 2
	local halign, valign = params.halign or 0.5, params.valign or 0.5
	local maxChars = params.maxChars or 16
	local perFace = math.ceil(maxChars / 2)
	local faces = VOLT26.CutoutMetrics and VOLT26.CutoutMetrics.faces or {}

	-- Draw at the display's resolution, not the theme's, so the sprite maps
	-- 1:1 onto screen pixels.
	local scale = 1
	if DISPLAY and DISPLAY.GetDisplayHeight then
		scale = math.min(3, math.max(1, DISPLAY:GetDisplayHeight() / SCREEN_HEIGHT))
	end
	local margin = 2
	local texW = math.ceil(maxW * scale) + margin * 2
	local texH = math.ceil(maxH * scale) + margin * 2

	local state = {
		text = nil, layout = nil, passes = nil, pass = 0,
		stamps = {}, -- stamps[face][k] = {frame, quad, text}
	}

	local function place(layout, offset)
		local o = layout.options
		local outline = layout.outline
		local used = {}
		for f = 1, #faces do used[f] = 0 end
		for f = 1, #faces do
			for _, stamp in ipairs(state.stamps[f]) do stamp.frame:visible(false) end
		end
		for i, g in ipairs(layout.glyphs) do
			used[g.face] = used[g.face] + 1
			local stamp = state.stamps[g.face][used[g.face]]
			if stamp then
				local dx, dy = 0, 0
				if offset then dx, dy = offset[1], offset[2] end
				-- Ring stamps draw plain letters only; boxes are already grown
				-- by their own backing rectangle on the centre stamps.
				local show = (not offset) or offset[3] or not g.box
				stamp.frame:visible(show):draworder(i)
					:xy(g.x + g.w / 2 + dx, layout.baseline + g.dy + dy):rotationz(g.rot)
				stamp.text:settext(g.ch):zoom(g.px / VOLT26.CutoutMetrics.em)
				local grow = 0
				if offset then grow = outline * 0.8 end
				if g.box then
					stamp.quad:visible(true)
						:zoomto(g.w + 2 * (g.pad + grow), g.asc + g.desc + 2 * (g.pad + grow))
						:y((g.desc - g.asc) / 2)
						:diffuse(offset and o.bk or o.fg)
				else
					stamp.quad:visible(false)
				end
				if offset or g.box then
					stamp.text:diffuse(o.bk)
				else
					stamp.text:diffuse(o.fg)
				end
			end
		end
		state.block:SortByDrawOrder()
	end

	local function frameBlock(layout)
		local b = layout.bounds
		local fit = math.min(1, maxW / (b[3] - b[1]), maxH / (b[4] - b[2]))
		local zoom = fit * scale
		local x = (margin - b[1] * zoom) * (1 - halign) + (texW - margin - b[3] * zoom) * halign
		if halign == 0.5 then x = texW / 2 - (b[1] + b[3]) / 2 * zoom end
		local y = (margin - b[2] * zoom) * (1 - valign) + (texH - margin - b[4] * zoom) * valign
		if valign == 0.5 then y = texH / 2 - (b[2] + b[4]) / 2 * zoom end
		state.tilt:xy(x, y):zoom(zoom):rotationz(layout.options.tiltDeg)
		state.block:xy(-layout.width / 2, -layout.height / 2)
	end

	local function showPlain(text)
		state.sprite:visible(false)
		state.aft:visible(false)
		state.passes = nil
		state.plain:visible(true):settext(text or "")
	end

	local function update(slot)
		-- A hidden slot is not drawn, so a pass would be lost: wait until shown.
		if not state.passes or not slot:GetVisible() then return end
		state.pass = state.pass + 1
		local pass = state.passes[state.pass]
		if not pass then
			state.passes = nil
			state.aft:visible(false)
			state.sprite:visible(true)
			return
		end
		state.clear:visible(state.pass == 1)
		place(state.layout, pass.offset)
		state.aft:visible(true)
	end

	-- One BitmapText per face per stamp: a BitmapText's face is fixed when it is
	-- built, and no face can appear more than every other letter.
	local block = Def.ActorFrame{
		InitCommand=function(self) state.block = self end,
	}
	for f, face in ipairs(faces) do
		for k = 1, perFace do
			block[#block+1] = Def.ActorFrame{
				InitCommand=function(self)
					state.stamps[f] = state.stamps[f] or {}
					state.stamps[f][k] = {
						frame = self,
						quad = self:GetChild("Box"),
						text = self:GetChild("Letter"),
					}
					self:visible(false)
				end,
				Def.Quad{ Name="Box" },
				LoadFont(face.font)..{
					Name="Letter",
					-- Bottom alignment puts the baseline of a single line at y=0.
					InitCommand=function(self) self:halign(0.5):valign(1):settext("") end,
				},
			}
		end
	end

	return Def.ActorFrame{
		InitCommand=function(self)
			state.self = self
			if params.x then self:xy(params.x, params.y or 0) end
			self:SetUpdateFunction(update)
			if params.onInit then params.onInit(self) end
		end,
		CutoutSetCommand=function(self, p)
			local text = p and p.text or ""
			if text == state.text then return end
			state.text = text
			local chars = select(2, text:gsub("[^\128-\191]", ""))
			local layout = chars <= maxChars and Cutout.Layout(text, opts) or nil
			if not layout then
				showPlain(text)
				return
			end
			state.plain:visible(false)
			state.layout = layout
			frameBlock(layout)
			state.passes = {}
			for _, offset in ipairs(backingOffsets(layout.outline)) do
				state.passes[#state.passes+1] = {offset = offset}
			end
			state.passes[#state.passes+1] = {offset = nil}
			state.pass = 0
			state.sprite:visible(false)
		end,

		Def.ActorFrameTexture{
			InitCommand=function(self)
				state.aft = self
				self:setsize(texW, texH)
				self:SetTextureName(textureName)
				self:EnableAlphaBuffer(true)
				-- Each pass adds a stamp; the first pass clears the texture.
				self:EnablePreserveTexture(true)
				self:Create()
				self:visible(false)
			end,
			Def.Quad{
				InitCommand=function(self)
					state.clear = self
					self:halign(0):valign(0):zoomto(texW, texH)
						:diffuse(0, 0, 0, 0):blend("BlendMode_CopySrc"):visible(false)
				end,
			},
			Def.ActorFrame{
				InitCommand=function(self) state.tilt = self end,
				block,
			},
		},
		Def.Sprite{
			InitCommand=function(self)
				state.sprite = self
				self:SetTexture(state.aft:GetTexture())
				self:align(halign, valign):zoom(1 / scale):visible(false)
			end,
		},
		LoadFont(params.fallbackFont or "Common Normal")..{
			InitCommand=function(self)
				state.plain = self
				self:align(halign, valign):visible(false)
				if params.fallbackZoom then self:zoom(params.fallbackZoom) end
				self:maxwidth(maxW / (params.fallbackZoom or 1))
			end,
		},
	}
end
