"""Build the notes radar art from the owner's Illustrator document.

Input:  tools/notes-radar/art/radar.svg  (the Illustrator document saved/exported as SVG)
Output: Graphics/VOLT26/SongSelection/NotesRadar/backdrop.png  - the owner's dark star + glow
        Graphics/VOLT26/SongSelection/NotesRadar/labels.png    - axis names + icons
        BGAnimations/ScreenSelectMusic overlay/VOLT26/RadarArt.lua - star geometry for the orange star

Both pictures share one frame: SIZE x SIZE pixels, centred on the orange star's
centre, ART_RADIUS_PX pixels per "radar radius" (the mean of the dark star's
five points).  Nothing is redrawn or regularised: the dark star is the owner's,
and the orange star is aimed at that star's own points and valleys, so a chart
full on every axis fills it exactly.

    python tools/notes-radar/build_radar_art.py    (cairosvg, lxml, numpy, Pillow)

If the artwork's structure changes, re-check the ELEMENT lists and the star
anchors below against the SVG (see docs/notes-radar.md).
"""
import copy, io, math, os, sys
import numpy as np, cairosvg
from lxml import etree
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SVG = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "art", "radar.svg")
GFX = os.path.join(ROOT, "Graphics", "VOLT26", "SongSelection", "NotesRadar")
LUA = os.path.join(ROOT, "BGAnimations", "ScreenSelectMusic overlay", "VOLT26", "RadarArt.lua")

SIZE = 1024
ART_RADIUS_PX = 300

# Top-level positions in radar.svg.
BACKDROP_ELEMENTS = [0]                       # glow image + dark star polyline
LABEL_ELEMENTS = [1, 2, 3, 4, 72, 73,         # icons
                  67, 68, 69, 70, 74]         # axis-name images

# The orange star's centre (the vertex all its facets share).
CENTRE = (5939.58, 3326.06)
# The dark star's anchors, clockwise from the top point, as drawn.  The lower
# right point is flat; its middle is used.
TIPS = [(6022.73, 2931.19), (6400.11, 3234.77), (6116.165, 3686.10),
        (5605.46, 3654.26), (5594.09, 3159.74)]
# VALLEYS[i] lies between TIPS[i] and TIPS[i+1].
VALLEYS = [(6067.02, 3189.30), (6113.63, 3389.38), (5915.82, 3501.93),
           (5779.40, 3347.32), (5879.44, 3179.06)]


def main():
    tree = etree.parse(SVG, etree.XMLParser(huge_tree=True))
    root = tree.getroot()
    kids = list(root)
    C = np.array(CENTRE)
    radius = float(np.mean([np.hypot(*(np.array(t) - C)) for t in TIPS]))
    half = radius * (SIZE / 2) / ART_RADIUS_PX
    view = (C[0] - half, C[1] - half, 2 * half, 2 * half)

    def render(indices):
        svg = etree.Element(root.tag, nsmap=root.nsmap)
        for k, v in root.attrib.items():
            svg.set(k, v)
        svg.set("viewBox", "%f %f %f %f" % view)
        svg.set("width", str(SIZE)); svg.set("height", str(SIZE))
        for i in indices:
            svg.append(copy.deepcopy(kids[i]))
        png = cairosvg.svg2png(bytestring=etree.tostring(svg), output_width=SIZE, output_height=SIZE)
        return Image.open(io.BytesIO(png)).convert("RGBA")

    os.makedirs(GFX, exist_ok=True)
    backdrop = render(BACKDROP_ELEMENTS); backdrop.save(os.path.join(GFX, "backdrop.png"), optimize=True)
    labels = render(LABEL_ELEMENTS); labels.save(os.path.join(GFX, "labels.png"), optimize=True)

    # How far the pictures reach from the centre, in radar radii, for layout.
    alpha = np.maximum(np.array(backdrop)[..., 3], np.array(labels)[..., 3])
    ys, xs = np.nonzero(alpha > 48)
    centre_px = SIZE / 2
    reach = {
        "Left": (centre_px - xs.min()) / ART_RADIUS_PX, "Right": (xs.max() - centre_px) / ART_RADIUS_PX,
        "Up": (centre_px - ys.min()) / ART_RADIUS_PX, "Down": (ys.max() - centre_px) / ART_RADIUS_PX,
    }

    def unit(points):
        return ["{%.4f, %.4f}" % tuple((np.array(p) - C) / radius) for p in points]

    lua = """-- Generated by tools/notes-radar/build_radar_art.py from the owner's artwork.
-- Do not edit by hand: change the artwork and rebuild.
--
-- Every figure is in radar radii (the mean distance of the dark star's five
-- points from the centre), measured from the centre of the star, with y down.
-- backdrop.png and labels.png are centred on the same point, ArtRadius pixels
-- to one radar radius.
return {
	ArtRadius = %d,
	-- The dark star's points, clockwise from the top: STREAM, XOVER,
	-- FOOTSWITCH, BRACKETS, SIDESWITCH.
	Tips = { %s },
	-- Valleys[i] lies between Tips[i] and Tips[i+1].
	Valleys = { %s },
	-- How far the backdrop and the labels reach, for fitting the radar.
	Reach = { Left = %.3f, Right = %.3f, Up = %.3f, Down = %.3f },
}
""" % (ART_RADIUS_PX, ", ".join(unit(TIPS)), ", ".join(unit(VALLEYS)),
       reach["Left"], reach["Right"], reach["Up"], reach["Down"])
    with open(LUA, "w", newline="\n") as f:
        f.write(lua)
    print("radius", round(radius, 1), "reach", {k: round(v, 3) for k, v in reach.items()})
    print("wrote", GFX, "and", LUA)


if __name__ == "__main__":
    main()
