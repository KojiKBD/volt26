"""Read style face textures and generate geometry excluding their flat red field.

The source PNGs are only read. Output is Lua rectangle geometry, not edited images.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
BACKGROUND = (228, 0, 1)
output = ["-- Generated by tools/style-select/build-foreground-mesh.py.", "return {"]
for name in ("single", "versus", "double"):
    image = Image.open(ROOT / f"Graphics/VOLT26/StyleSelect/face_{name}.png").convert("RGB")
    pixels = image.load()
    rectangles, active = [], {}
    for y in range(image.height):
        spans, start = [], None
        for x in range(image.width + 1):
            foreground = x < image.width and pixels[x, y] != BACKGROUND
            if foreground and start is None:
                start = x
            elif not foreground and start is not None:
                spans.append((start, x))
                start = None
        next_active = {}
        for span in spans:
            rectangle = active.pop(span, None)
            if rectangle is None:
                rectangle = [span[0], y, span[1] - span[0], 1]
            else:
                rectangle[3] += 1
            next_active[span] = rectangle
        rectangles.extend(active.values())
        active = next_active
    rectangles.extend(active.values())
    output.append(f"    {name} = {{")
    output.extend("        {" + ",".join(map(str, r)) + "}," for r in rectangles)
    output.append("    },")
    print(f"{name}: {len(rectangles)} foreground rectangles")
output.append("}")
(ROOT / "BGAnimations/ScreenSelectStyle underlay/ForegroundGeometry.lua").write_text(
    "\n".join(output) + "\n", encoding="utf-8"
)
